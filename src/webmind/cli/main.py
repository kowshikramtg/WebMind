"""``webmind`` command-line interface."""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import secrets
import shutil
import sys
from pathlib import Path
from typing import Any

import yaml

from webmind.core.errors import ConfigurationError, WebMindError
from webmind.version import __version__

TEMPLATE = """# WebMind configuration — generated by `webmind init`.
# Full reference: docs/configuration.md. Secrets come from environment variables / .env.

app:
  name: {name}
  environment: development

server:
  host: 127.0.0.1
  port: 8080
  cors_origins: []                       # e.g. ["https://www.example.org"]
  admin_api_key: ${{WEBMIND_ADMIN_API_KEY:-}}

database:
  url: ${{WEBMIND_DATABASE_URL:-sqlite:///./data/webmind.db}}

vector_store:
  provider: database                     # or pgvector (requires PostgreSQL)

object_store:
  provider: local
  path: ./data/objects

llm:
  provider: {llm_provider}               # none | ollama | openai | anthropic
{llm_block}
embeddings:
  provider: hashing                      # hashing | ollama | openai | sentence_transformers

retrieval:
  hybrid_search: true
  top_k: 6

security:
  authentication:
    mode: {auth_mode}
    allow_anonymous: true
    anonymous_roles: [public]
{jwt_block}  roles:
    public:
      capabilities: [chat, search, navigate, "documents:read"]
    member:
      inherits: [public]
      capabilities: ["records:read", analytics, export]
    admin:
      inherits: [member]
      capabilities: [reports, "sync:status"]

sources:
{source_block}
datasets: []
"""


def _ask(prompt: str, default: str, interactive: bool) -> str:
    if not interactive:
        return default
    val = input(f"{prompt} [{default}]: ").strip()
    return val or default


def cmd_init(args: argparse.Namespace) -> int:
    target = Path(args.directory).resolve()
    target.mkdir(parents=True, exist_ok=True)
    cfg_path = target / "webmind.yaml"
    if cfg_path.exists() and not args.force:
        print(f"{cfg_path} already exists (use --force to overwrite)", file=sys.stderr)
        return 1
    interactive = not args.yes and sys.stdin.isatty()
    name = _ask("Application name", target.name or "webmind", interactive)
    source_kind = _ask("Content source: website URL or local folder path", args.source or "./site", interactive)
    llm = _ask("LLM provider (none/ollama/openai/anthropic)", args.llm or "none", interactive)
    auth = _ask("Authentication (public/host_application)", args.auth or "public", interactive)

    if source_kind.startswith(("http://", "https://")):
        source_block = (
            f"  - id: website\n    type: website\n    url: {source_kind}\n    access: {{ visibility: public }}\n"
        )
    else:
        source_block = (
            f"  - id: content\n    type: filesystem\n    path: {source_kind}\n"
            '    patterns: ["**/*.html", "**/*.md", "**/*.txt", "**/*.pdf"]\n'
            "    access: { visibility: public }\n"
        )
    llm_block = {
        "none": "",
        "ollama": "  model: ${WEBMIND_LLM_MODEL:-llama3.1}\n  base_url: ${OLLAMA_URL:-http://localhost:11434}\n",
        "openai": "  model: ${WEBMIND_LLM_MODEL:-gpt-4o-mini}\n  base_url: ${WEBMIND_LLM_BASE_URL:-https://api.openai.com/v1}\n  api_key: ${WEBMIND_LLM_API_KEY}\n",
        "anthropic": "  model: ${WEBMIND_LLM_MODEL:-claude-opus-5-5}\n  api_key: ${ANTHROPIC_API_KEY}\n",
    }.get(llm)
    if llm_block is None:
        print(f"unknown llm provider: {llm}", file=sys.stderr)
        return 2
    jwt_block = (
        "    jwt:\n      algorithms: [HS256]\n      secret: ${WEBMIND_JWT_SECRET}\n"
        if auth == "host_application"
        else ""
    )
    cfg_path.write_text(
        TEMPLATE.format(
            name=name,
            llm_provider=llm,
            llm_block=llm_block,
            auth_mode=auth,
            jwt_block=jwt_block,
            source_block=source_block,
        ),
        encoding="utf-8",
    )
    env_path = target / ".env"
    if not env_path.exists():
        env_path.write_text(
            "# Local secrets for WebMind — never commit this file.\n"
            f"WEBMIND_ADMIN_API_KEY={secrets.token_urlsafe(32)}\n"
            f"WEBMIND_JWT_SECRET={secrets.token_urlsafe(48)}\n",
            encoding="utf-8",
        )
        try:
            os.chmod(env_path, 0o600)
        except OSError:
            pass
    (target / "data").mkdir(exist_ok=True)
    gi = target / ".gitignore"
    lines = gi.read_text(encoding="utf-8").splitlines() if gi.exists() else []
    for entry in (".env", "data/"):
        if entry not in lines:
            lines.append(entry)
    gi.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Created {cfg_path}\nCreated {env_path} with random secrets (git-ignored)\n")
    print("Next steps:\n  webmind doctor\n  webmind index\n  webmind serve")
    return 0


def _load(args: argparse.Namespace):  # noqa: ANN202
    from webmind.core.config import load_config

    return load_config(args.config)


def _runtime(args: argparse.Namespace):  # noqa: ANN202
    from webmind.runtime import WebMindRuntime

    return WebMindRuntime(_load(args))


def cmd_serve(args: argparse.Namespace) -> int:
    import uvicorn

    from webmind.api.app import create_app

    cfg = _load(args)
    app = create_app(cfg)
    host = args.host or cfg.server.host
    port = args.port or cfg.server.port
    if host not in ("127.0.0.1", "localhost", "::1") and cfg.server.admin_api_key is None:
        print("note: admin API disabled (server.admin_api_key unset)", file=sys.stderr)
    uvicorn.run(
        app,
        host=host,
        port=port,
        log_level=args.log_level,
        proxy_headers=args.proxy_headers,
        forwarded_allow_ips=os.environ.get("FORWARDED_ALLOW_IPS", "127.0.0.1"),
    )
    return 0


def _print_reports(reports: list[Any]) -> int:
    failed = 0
    for r in reports:
        d = r.as_dict()
        print(
            f"[{d['source_id']}] {d['status']}: discovered={d['discovered']} new={d['new']} changed={d['changed']} "
            f"unchanged={d['unchanged']} not_modified={d['not_modified']} deleted={d['deleted']} "
            f"errors={d['errors']} ({d['duration_ms']} ms)"
        )
        for e in d["error_samples"]:
            print(f"    ! {e}")
        failed += d["status"] == "failed"
    return 1 if failed else 0


def cmd_index(args: argparse.Namespace) -> int:
    async def run() -> int:
        rt = _runtime(args)
        try:
            await rt.initialize()
            if args.reembed:
                n = await rt.reembed()
                print(f"re-embedded {n} chunks with {rt.embedder.model_id}")
                return 0
            return _print_reports(await rt.sync(args.source, trigger="cli", rebuild=args.rebuild))
        finally:
            await rt.close()

    return asyncio.run(run())


def cmd_sync(args: argparse.Namespace) -> int:
    async def run() -> int:
        rt = _runtime(args)
        try:
            return _print_reports(await rt.sync(args.source, trigger="cli", uris=args.uri or None))
        finally:
            await rt.close()

    return asyncio.run(run())


def cmd_doctor(args: argparse.Namespace) -> int:
    problems = 0
    warnings = 0

    def ok(msg: str) -> None:
        print(f"  ✔ {msg}")

    def warn(msg: str) -> None:
        nonlocal warnings
        warnings += 1
        print(f"  ! {msg}")

    def bad(msg: str) -> None:
        nonlocal problems
        problems += 1
        print(f"  ✘ {msg}")

    print(f"WebMind {__version__} — doctor")
    try:
        cfg = _load(args)
        ok(f"configuration valid ({args.config})")
    except ConfigurationError as exc:
        bad(str(exc))
        return 1

    async def checks() -> None:
        from webmind.runtime import WebMindRuntime

        try:
            rt = WebMindRuntime(cfg)
        except WebMindError as exc:
            bad(f"runtime: {exc}")
            return
        try:
            await rt.initialize()
            ok(f"metadata database reachable ({rt.db.dialect})")
            ok("keyword index available") if rt.db.check_fts() else bad("keyword index (FTS) unavailable")
            ok(f"embeddings: {rt.embedder.model_id}")
            if cfg.embeddings.provider == "hashing":
                warn(
                    "embeddings.provider=hashing is a lexical baseline; configure a neural embedding model for semantic search"
                )
            if rt.needs_reindex:
                bad("embedding model changed since indexing — run `webmind index --reembed`")
            if rt.llm is None:
                warn("llm.provider=none: answers are extractive (quoted passages, no summarization)")
            else:
                try:
                    res = await rt.llm.generate(
                        [
                            __import__("webmind.providers.base", fromlist=["ChatMessage"]).ChatMessage(
                                role="user", content="Reply with OK"
                            )
                        ],
                        max_tokens=256,
                    )
                    ok(f"llm reachable: {rt.llm.info.provider}/{rt.llm.info.model} → {res.text.strip()[:20]!r}")
                except Exception as exc:
                    bad(f"llm unreachable: {exc}")
            for src in cfg.sources:
                if src.type == "filesystem":
                    p = cfg.resolve_path(src.path)
                    ok(f"source '{src.id}': {p}") if p.is_dir() else bad(f"source '{src.id}': directory not found: {p}")
                else:
                    ok(f"source '{src.id}': {src.url}")
            for ds in cfg.datasets:
                try:
                    rt.datasets._engine(ds).connect().close()
                    ok(f"dataset '{ds.id}' reachable (read-only)")
                except Exception as exc:
                    bad(f"dataset '{ds.id}': {type(exc).__name__}: {exc}")
            auth = cfg.security.authentication
            if auth.mode == "host_application":
                ok(f"host-application tokens: {', '.join(auth.jwt.algorithms)}")
                secret = auth.jwt.secret.get_secret_value() if auth.jwt.secret else ""
                if "demo" in secret or "change-me" in secret:
                    warn("JWT secret looks like a placeholder — generate a random one for production")
            else:
                ok("public mode: anonymous visitors only see public content")
            if cfg.server.admin_api_key is None:
                warn("server.admin_api_key not set: admin endpoints disabled")
            if cfg.app.environment == "production" and cfg.server.host == "0.0.0.0" and not cfg.server.cors_origins:  # noqa: S104
                warn("listening on all interfaces without CORS origins; put WebMind behind your reverse proxy")
            if cfg.telemetry.enabled:
                warn("telemetry enabled — data goes only to your configured OTLP endpoint")
            else:
                ok("no telemetry is sent anywhere")
        finally:
            await rt.close()

    asyncio.run(checks())
    print(f"\n{problems} problem(s), {warnings} warning(s)")
    return 1 if problems else 0


def cmd_connectors(args: argparse.Namespace) -> int:
    if args.action == "list":
        cfg = _load(args)
        if not cfg.sources:
            print("no sources configured")
        for s in cfg.sources:
            where = getattr(s, "url", None) or getattr(s, "path", "")
            interval = f", every {s.sync.interval_minutes} min" if s.sync.interval_minutes else ""
            print(
                f"{s.id:20} {s.type:11} {where}  (tenant: {cfg.tenant_of(s)}, access: {s.access.visibility}{interval})"
            )
        return 0
    # add
    path = Path(args.config)
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    entry: dict[str, Any] = {"id": args.id, "type": args.type, "access": {"visibility": args.visibility}}
    if args.type == "website":
        if not args.url:
            print("--url is required for website sources", file=sys.stderr)
            return 2
        entry["url"] = args.url
    else:
        if not args.path:
            print("--path is required for filesystem sources", file=sys.stderr)
            return 2
        entry["path"] = args.path
    if args.visibility == "restricted" and args.roles:
        entry["access"]["roles"] = args.roles
    if any(s.get("id") == args.id for s in raw.get("sources", []) or []):
        print(f"source '{args.id}' already exists", file=sys.stderr)
        return 1
    raw.setdefault("sources", []).append(entry)
    from webmind.core.config import config_from_dict

    config_from_dict(raw, base_dir=path.parent)  # validate before writing
    shutil.copyfile(path, path.with_suffix(path.suffix + ".bak"))
    path.write_text(yaml.safe_dump(raw, sort_keys=False), encoding="utf-8")
    print(f"added source '{args.id}' (backup: {path.name}.bak; note: YAML comments are not preserved)")
    return 0


def cmd_token(args: argparse.Namespace) -> int:
    """Mint a short-lived user token for local testing (HS* configs only)."""
    from webmind.security.identity import issue_token

    cfg = _load(args)
    jcfg = cfg.security.authentication.jwt
    if cfg.security.authentication.mode != "host_application" or jcfg.secret is None:
        print("token minting needs authentication.mode=host_application with an HS* secret", file=sys.stderr)
        return 2
    attrs = {}
    for kv in args.attr or []:
        k, _, v = kv.partition("=")
        attrs[k] = v
    print(
        issue_token(
            jcfg.secret.get_secret_value(),
            user_id=args.user,
            roles=args.role or [],
            attributes=attrs,
            tenant=args.tenant,
            ttl_seconds=min(args.ttl, jcfg.max_token_lifetime_seconds),
            algorithm=jcfg.algorithms[0],
            issuer=jcfg.issuer,
            audience=jcfg.audience,
        )
    )
    return 0


def cmd_ask(args: argparse.Namespace) -> int:
    from webmind.sdk import WebMind

    async def run() -> int:
        cfg = _load(args)
        wm = WebMind(cfg)
        try:
            await wm.initialize()
            attrs = dict(kv.partition("=")[::2] for kv in (args.attr or []))
            res = await wm.ask(args.question, user_id=args.user, roles=args.role or [], attributes=attrs)
            if args.json:
                print(res.model_dump_json(indent=2))
            else:
                print(res.answer)
                for c in res.citations:
                    print(f"  [{c.index}] {c.title or ''}{' — ' + c.section if c.section else ''} {c.url or ''}")
            return 0
        finally:
            await wm.close()

    return asyncio.run(run())


def cmd_eval(args: argparse.Namespace) -> int:
    from webmind.evaluation import run_retrieval_eval

    async def run() -> int:
        rt = _runtime(args)
        try:
            await rt.initialize()
            report = await run_retrieval_eval(rt, Path(args.dataset), k=args.k)
            print(json.dumps(report, indent=2))
            return 0
        finally:
            await rt.close()

    return asyncio.run(run())


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="webmind", description="WebMind — self-hosted website intelligence")
    p.add_argument("--version", action="version", version=f"webmind {__version__}")
    sub = p.add_subparsers(dest="command", required=True)

    def with_config(sp: argparse.ArgumentParser) -> argparse.ArgumentParser:
        sp.add_argument("--config", "-c", default=os.environ.get("WEBMIND_CONFIG", "webmind.yaml"))
        return sp

    sp = sub.add_parser("init", help="create webmind.yaml and .env in a directory")
    sp.add_argument("directory", nargs="?", default=".")
    sp.add_argument("--source", help="website URL or local folder")
    sp.add_argument("--llm", choices=["none", "ollama", "openai", "anthropic"])
    sp.add_argument("--auth", choices=["public", "host_application"])
    sp.add_argument("--yes", "-y", action="store_true", help="non-interactive; accept defaults")
    sp.add_argument("--force", action="store_true")
    sp.set_defaults(func=cmd_init)

    sp = with_config(sub.add_parser("serve", help="run the HTTP API"))
    sp.add_argument("--host")
    sp.add_argument("--port", type=int)
    sp.add_argument("--log-level", default="info")
    sp.add_argument("--proxy-headers", action="store_true", help="trust X-Forwarded-* from FORWARDED_ALLOW_IPS")
    sp.set_defaults(func=cmd_serve)

    sp = with_config(sub.add_parser("doctor", help="validate configuration and connectivity"))
    sp.set_defaults(func=cmd_doctor)

    sp = with_config(sub.add_parser("index", help="ingest sources (initial or full re-index)"))
    sp.add_argument("--source")
    sp.add_argument("--rebuild", action="store_true", help="reprocess every resource even if unchanged")
    sp.add_argument("--reembed", action="store_true", help="re-embed existing chunks with the current model")
    sp.set_defaults(func=cmd_index)

    sp = with_config(sub.add_parser("sync", help="incremental synchronization"))
    sp.add_argument("--source")
    sp.add_argument("--uri", action="append", help="sync only these resource URIs (repeatable)")
    sp.set_defaults(func=cmd_sync)

    sp = with_config(sub.add_parser("connectors", help="list or add sources"))
    sp.add_argument("action", choices=["list", "add"])
    sp.add_argument("--id")
    sp.add_argument("--type", choices=["website", "filesystem"], default="website")
    sp.add_argument("--url")
    sp.add_argument("--path")
    sp.add_argument("--visibility", choices=["public", "restricted"], default="public")
    sp.add_argument("--roles", nargs="*")
    sp.set_defaults(func=cmd_connectors)

    sp = with_config(sub.add_parser("token", help="mint a test user token (development)"))
    sp.add_argument("--user", required=True)
    sp.add_argument("--role", action="append")
    sp.add_argument("--attr", action="append", help="attribute key=value (repeatable)")
    sp.add_argument("--tenant")
    sp.add_argument("--ttl", type=int, default=900)
    sp.set_defaults(func=cmd_token)

    sp = with_config(sub.add_parser("ask", help="ask a question from the terminal"))
    sp.add_argument("question")
    sp.add_argument("--user")
    sp.add_argument("--role", action="append")
    sp.add_argument("--attr", action="append")
    sp.add_argument("--json", action="store_true")
    sp.set_defaults(func=cmd_ask)

    sp = with_config(sub.add_parser("eval", help="retrieval evaluation (recall@k, MRR, nDCG)"))
    sp.add_argument("dataset", help="JSON/JSONL file of {question, expected: [url substrings]}")
    sp.add_argument("-k", type=int, default=5)
    sp.set_defaults(func=cmd_eval)
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.command == "connectors" and args.action == "add" and not args.id:
        print("--id is required", file=sys.stderr)
        return 2
    try:
        return int(args.func(args) or 0)
    except ConfigurationError as exc:
        print(f"configuration error: {exc}", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
